from datetime import date

import pytest

from text2sql.semantic.timeparse import baseline_range, is_month_aligned, parse_time, vague_time_word

D = date


@pytest.mark.parametrize(
    "text, start, end",
    [
        # absolute
        ("1998年11月的风险事件数是多少？", D(1998, 11, 1), D(1998, 11, 30)),
        ("1997年不良贷款金额", D(1997, 1, 1), D(1997, 12, 31)),
        ("97年各大区的不良率", D(1997, 1, 1), D(1997, 12, 31)),
        ("1998年第三季度各地区风险涉及金额", D(1998, 7, 1), D(1998, 9, 30)),
        ("1997年第四季度风险账户数", D(1997, 10, 1), D(1997, 12, 31)),
        ("1996年Q2", D(1996, 4, 1), D(1996, 6, 30)),
        ("1998年上半年每月的现金取现笔数", D(1998, 1, 1), D(1998, 6, 30)),
        ("1998年下半年", D(1998, 7, 1), D(1998, 12, 31)),
        ("1996年各季度的活跃账户数", D(1996, 1, 1), D(1996, 12, 31)),
        ("1998年12月每天的交易笔数", D(1998, 12, 1), D(1998, 12, 31)),
        ("1998年十二月", D(1998, 12, 1), D(1998, 12, 31)),
        ("1998年3月15日", D(1998, 3, 15), D(1998, 3, 15)),
        ("1998-03", D(1998, 3, 1), D(1998, 3, 31)),
        # ranges
        ("1995年到1997年每年的放款笔数", D(1995, 1, 1), D(1997, 12, 31)),
        ("1996年到1998年每年的发卡量", D(1996, 1, 1), D(1998, 12, 31)),
        ("1995-1997年", D(1995, 1, 1), D(1997, 12, 31)),
        ("1998年12月1日到12月15日的交易金额", D(1998, 12, 1), D(1998, 12, 15)),
        ("1997年2月至12月，每月现金取现金额", D(1997, 2, 1), D(1997, 12, 31)),
        ("1997年1-6月", D(1997, 1, 1), D(1997, 6, 30)),
        ("1996年3月到1997年2月", D(1996, 3, 1), D(1997, 2, 28)),
        ("1998-12-01至1998-12-15", D(1998, 12, 1), D(1998, 12, 15)),
        # relative to 1998-12-31
        ("上个月风险涉及金额是多少？", D(1998, 11, 1), D(1998, 11, 30)),
        ("上月", D(1998, 11, 1), D(1998, 11, 30)),
        ("本月", D(1998, 12, 1), D(1998, 12, 31)),
        ("近三个月的风险事件数", D(1998, 10, 1), D(1998, 12, 31)),
        ("最近6个月", D(1998, 7, 1), D(1998, 12, 31)),
        ("近半年每月的入账金额趋势", D(1998, 7, 1), D(1998, 12, 31)),
        ("今年以来的放款金额是多少？", D(1998, 1, 1), D(1998, 12, 31)),
        ("今年贷款规模怎么样", D(1998, 1, 1), D(1998, 12, 31)),
        ("去年", D(1997, 1, 1), D(1997, 12, 31)),
        ("去年12月", D(1997, 12, 1), D(1997, 12, 31)),
        ("前年第一季度", D(1996, 1, 1), D(1996, 3, 31)),
        ("上季度交易量同比怎么样？", D(1998, 7, 1), D(1998, 9, 30)),
        ("本季度", D(1998, 10, 1), D(1998, 12, 31)),
        ("近一年", D(1998, 1, 1), D(1998, 12, 31)),
        ("近7天", D(1998, 12, 25), D(1998, 12, 31)),
        ("昨天", D(1998, 12, 30), D(1998, 12, 30)),
        ("近12年", D(1987, 1, 1), D(1998, 12, 31)),  # never read as the year 2012
        ("去年到今年", D(1997, 1, 1), D(1998, 12, 31)),
    ],
)
def test_parse_time(text, start, end):
    span = parse_time(text)
    assert span is not None, text
    assert (span.start, span.end) == (start, end)


@pytest.mark.parametrize(
    "text",
    ["各卡等级的发卡量是多少？", "月还款额超过5000的贷款", "贷款期限为12个月的放款金额", "最近的风险情况如何？",
     "按月出账单的账户", "每月的交易", "1998年2月30日", None, ""],
)
def test_no_time_expression(text):
    assert parse_time(text) is None


def test_baselines():
    assert baseline_range(D(1998, 11, 1), D(1998, 11, 30), "mom") == (D(1998, 10, 1), D(1998, 10, 31))
    assert baseline_range(D(1998, 7, 1), D(1998, 9, 30), "mom") == (D(1998, 4, 1), D(1998, 6, 30))
    assert baseline_range(D(1998, 1, 1), D(1998, 1, 31), "mom") == (D(1997, 12, 1), D(1997, 12, 31))
    assert baseline_range(D(1997, 1, 1), D(1997, 12, 31), "yoy") == (D(1996, 1, 1), D(1996, 12, 31))
    assert baseline_range(D(1996, 2, 29), D(1996, 2, 29), "yoy") == (D(1995, 2, 28), D(1995, 2, 28))
    assert baseline_range(D(1998, 12, 1), D(1998, 12, 15), "mom") == (D(1998, 11, 16), D(1998, 11, 30))


def test_month_alignment():
    assert is_month_aligned(D(1998, 10, 1), D(1998, 12, 31))
    assert not is_month_aligned(D(1998, 12, 1), D(1998, 12, 15))


@pytest.mark.parametrize("text, word", [
    ("最近的风险事件数是多少", "最近"),
    ("目前的不良率", "目前"),
    ("近期大额取现多吗", "近期"),
    ("最近3个月的风险事件数", None),  # parseable, so not vague
    ("1998年风险事件数", None),
])
def test_vague_time_words(text, word):
    assert vague_time_word(text) == word
